T("vec.col", C6, "6.2", "向量共线定理", GG, "reasoning",
  "知道非零向量 b 与 a 共线，当且仅当存在实数 λ 使 b=λa。",
  ["能判断一个向量是否为另一个的实数倍", "能求出这个倍数"],
  "GA.02", "inferred", "共线定理是数乘的判定用法。待核。")
Qs("vec.col", [
    n("向量 (2，4) 是 (1，2) 的多少倍？", "2",
      "2×(1，2)=(2，4)，倍数是 2，所以共线。"),
    n("若 (k，6) 与 (2，3) 共线，且由第二坐标得 k/2=6/3。k 是多少？", "2*(6/3)",
      "对应坐标成比例，k/2=2，k=4。"),
    c("(1，0) 与 (0，1) 是否共线？", "不共线", ["共线", "只有在起点相同时共线", "方向相反所以共线"],
      "不存在实数 λ 使 (0，1)=λ(1，0)，因为第一坐标会迫使 λ=0，第二坐标却是 1。"),
    c("零向量与任意向量的位置关系按共线定义？", "零向量与任意向量共线",
      ["只与零向量共线", "与任意向量垂直", "不能讨论"],
      "取 λ=0 就有 0=λa。教材把零向量看作与任意向量共线。"),
])

